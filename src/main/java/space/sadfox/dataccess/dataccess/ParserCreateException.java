package space.sadfox.dataccess.dataccess;

public class ParserCreateException extends ParserException {

  public ParserCreateException() {
  }

  public ParserCreateException(String message) {
    super(message);
  }

  public ParserCreateException(Throwable cause) {
    super(cause);
  }

  public ParserCreateException(String message, Throwable cause) {
    super(message, cause);
  }

  public ParserCreateException(String message, Throwable cause, boolean enableSuppression, boolean writableStackTrace) {
    super(message, cause, enableSuppression, writableStackTrace);
  }

}
