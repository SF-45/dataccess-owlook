package space.sadfox.dataccess.dataccess;

public class ParserProviderNotFound extends Exception {

	private static final long serialVersionUID = -2519364882881750347L;

	public ParserProviderNotFound() {
		super();
	}

	public ParserProviderNotFound(String message, Throwable cause, boolean enableSuppression,
			boolean writableStackTrace) {
		super(message, cause, enableSuppression, writableStackTrace);
	}

	public ParserProviderNotFound(String message, Throwable cause) {
		super(message, cause);
	}

	public ParserProviderNotFound(String message) {
		super(message);
	}

	public ParserProviderNotFound(Throwable cause) {
		super(cause);
	}

	
}
